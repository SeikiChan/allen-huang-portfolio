let currentLanguage = "zh";
const languageToggle = document.getElementById("language-toggle");
const screenLanguage = document.getElementById("screen-language");
const dashboardShot = document.getElementById("dashboard-shot");

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = copy[language].title;
  document.querySelector('meta[name="description"]').content = copy[language].description;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[language][key] !== undefined) element.innerHTML = copy[language][key];
  });

  languageToggle.textContent = language === "zh" ? "EN" : "中文";
  languageToggle.setAttribute("aria-label", language === "zh" ? "Switch language to English" : "切换到中文");
  dashboardShot.src = `assets/dashboard-latest-${language === "zh" ? "zh" : "en"}.png`;
  dashboardShot.alt = language === "zh"
    ? "AI News Radar 中文版研究简报界面截图"
    : "AI News Radar English research brief interface screenshot";
}

languageToggle.addEventListener("click", () => setLanguage(currentLanguage === "zh" ? "en" : "zh"));
screenLanguage.addEventListener("click", () => setLanguage(currentLanguage === "zh" ? "en" : "zh"));

setLanguage(currentLanguage);
